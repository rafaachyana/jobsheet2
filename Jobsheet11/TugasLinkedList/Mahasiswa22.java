package Jobsheet11.TugasLinkedList;

public class Mahasiswa22 {
    String nim, nama, kelas;
  
    public Mahasiswa22(String nim, String nama, String kelas) {
        this.nim = nim;
        this.nama = nama;
        this.kelas = kelas;
    }

    public void tampilInformasi() {
        System.out.println(nim + "\t" + nama + "\t" + kelas);
    }
}
